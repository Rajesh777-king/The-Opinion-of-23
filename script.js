function escapeHTML(value = "") {
  return String(value).replace(/[&<>"']/g, char => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    '"': "&quot;",
    "'": "&#039;"
  })[char]);
}

function renderCards(category = filter?.value || "All") {
  if (!grid) return;

  const visible = articles.filter(article =>
    category === "All" || article.category === category
  );

  grid.innerHTML = visible.map(article => `
    <article class="article-card">
      <a class="card-image"
         href="article.html?slug=${encodeURIComponent(article.slug)}">
        <img
          src="${escapeHTML(article.image)}"
          alt="${escapeHTML(article.alt)}"
          loading="lazy"
          onerror="this.parentElement.classList.add('image-fallback'); this.remove();">
        <span class="image-arrow" aria-hidden="true">↗</span>
      </a>

      <div class="card-body">
        <p class="card-meta">
          ${escapeHTML(article.category)}
          <span>·</span>
          ${escapeHTML(article.date)}
        </p>

        <h3>
          <a href="article.html?slug=${encodeURIComponent(article.slug)}">
            ${escapeHTML(article.title)}
          </a>
        </h3>

        <p>${escapeHTML(article.excerpt)}</p>

        <a class="text-link"
           href="article.html?slug=${encodeURIComponent(article.slug)}">
          ${ui.read}
        </a>
      </div>
    </article>
  `).join("");

  if (!visible.length) {
    grid.innerHTML = `<p>${ui.empty}</p>`;
  }
}

function renderArticle() {
  const articlePage = document.querySelector("#articlePage");
  if (!articlePage) return;

  const slug = new URLSearchParams(window.location.search).get("slug");
  const article = articles.find(item => item.slug === slug);

  if (!article) {
    articlePage.innerHTML = `
      <div class="not-found">
        <p class="eyebrow">404</p>
        <h1>${ui.notFound}</h1>
        <a class="text-link" href="index.html#articles">${ui.back}</a>
      </div>
    `;
    return;
  }

  document.title = `${article.title} — The Opinion of 23`;

  articlePage.innerHTML = `
    <a class="back-link" href="index.html#articles">${ui.back}</a>

    <header class="article-header">
      <p class="card-meta">
        ${escapeHTML(article.category)}
        <span>·</span>
        ${escapeHTML(article.date)}
      </p>

      <h1>${escapeHTML(article.title)}</h1>

      <p class="article-deck">${escapeHTML(article.excerpt)}</p>

      <p class="author-byline">${ui.author}</p>
    </header>

    <img
      class="article-cover"
      src="${escapeHTML(article.image)}"
      alt="${escapeHTML(article.alt)}">

    <div class="article-layout">
      <article class="article-content">
        ${article.paragraphs.map(paragraph =>
          `<p>${escapeHTML(paragraph)}</p>`
        ).join("")}



        <section class="comments-section">
          <p class="eyebrow">${ui.comments}</p>
          <h2>${ui.commentsTitle}</h2>
          <p>${ui.commentsHelp}</p>
          <div class="giscus">
            <p class="comments-placeholder">${ui.placeholder}</p>
          </div>
        </section>
      </article>


    </div>
  `;
}

// Populate the category filter without duplicating existing options.
if (filter) {
  const existingValues = new Set(
    [...filter.options].map(option => option.value)
  );

  [...new Set(articles.map(article => article.category))]
    .sort()
    .forEach(category => {
      if (existingValues.has(category)) return;

      const option = document.createElement("option");
      option.value = category;
      option.textContent = category;
      filter.appendChild(option);
    });

  filter.addEventListener("change", () => {
    renderCards(filter.value);
  });
}

// Render the homepage and individual article page when applicable.
renderCards();
